// 生成理论学院目录摘要（level/chapter 元数据，不含正文与小测）。
// 首页、store、成就检查只消费摘要；完整数据仍留在 variants/* 供章节页使用。
// 用法：pnpm theory:manifest（数据层改动后必须重新运行，守卫见 manifest.parity.test.ts）
import { createServer } from 'vite';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUT_DIR = path.join(ROOT, 'src/features/theory-academy/data/levels/manifest');

const HEADER = `// AUTO-GENERATED by scripts/generate-theory-manifest.mjs — do not edit.
// 数据层（variants/*）改动后运行 \`pnpm theory:manifest\` 重新生成。
import type { TheoryLevelSummary } from '../../../types';
`;

/**
 * 章节投影：只保留目录层字段。
 * `supplemental` / `pathTags` 为条件字段——缺省时不落盘，避免每章都写一对 undefined；
 * 字段顺序固定（variant 之后），保证同一份数据反复生成得到逐字节相同的文件。
 */
function projectChapter(chapter) {
  const projected = {
    id: chapter.id,
    level: chapter.level,
    order: chapter.order,
    title: chapter.title,
    subtitle: chapter.subtitle,
    duration: chapter.duration,
    variant: chapter.variant,
  };
  if (chapter.supplemental) projected.supplemental = true;
  if (chapter.pathTags?.length) projected.pathTags = chapter.pathTags;
  return projected;
}

function projectLevel(level) {
  return {
    id: level.id,
    level: level.level,
    tier: level.tier,
    title: level.title,
    description: level.description,
    icon: level.icon,
    unlockRequirement: level.unlockRequirement,
    variant: level.variant,
    practiceRecommendations: level.practiceRecommendations,
    chapters: level.chapters.map(projectChapter),
  };
}

/** 每个章节压成一行，避免生成文件触发 300 行规模守卫（Level 字段仍逐行可读） */
function serializeLevels(levels) {
  return levels
    .map((level) => {
      const chapters = level.chapters
        .map((chapter) => `      ${JSON.stringify(chapter)},`)
        .join('\n');
      return `  {
    "id": ${JSON.stringify(level.id)},
    "level": ${level.level},
    "tier": ${JSON.stringify(level.tier)},
    "title": ${JSON.stringify(level.title)},
    "description": ${JSON.stringify(level.description)},
    "icon": ${JSON.stringify(level.icon)},
    "unlockRequirement": ${JSON.stringify(level.unlockRequirement)},
    "variant": ${JSON.stringify(level.variant)},
    "practiceRecommendations": ${JSON.stringify(level.practiceRecommendations)},
    "chapters": [
${chapters}
    ]
  },`;
    })
    .join('\n');
}

const server = await createServer({
  root: ROOT,
  server: { middlewareMode: true },
  appType: 'custom',
  logLevel: 'silent',
});

try {
  const data = await server.ssrLoadModule(
    '/src/features/theory-academy/data/levels/variants/index.ts',
  );
  const variants = [
    ['standard', 'STANDARD_LEVEL_SUMMARIES', data.standardLevels],
    ['short-deck', 'SHORT_DECK_LEVEL_SUMMARIES', data.shortDeckLevels],
    ['heads-up', 'HEADS_UP_LEVEL_SUMMARIES', data.headsUpLevels],
  ];

  for (const [file, exportName, levels] of variants) {
    const projected = levels.map(projectLevel);
    const body = `${HEADER}\nexport const ${exportName}: TheoryLevelSummary[] = [\n${serializeLevels(
      projected,
    )}\n];\n`;
    writeFileSync(path.join(OUT_DIR, `${file}.ts`), body);
    console.log(
      `[theory-manifest] ${file}.ts ← ${projected.length} levels / ${projected.reduce(
        (sum, level) => sum + level.chapters.length,
        0,
      )} chapters`,
    );
  }
} finally {
  await server.close();
}
