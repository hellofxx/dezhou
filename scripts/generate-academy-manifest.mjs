// 生成策略学院目录摘要（Level/Lesson 元数据，不含正文/小测/练习）。
// 首页、store、成就检查、轨道/图谱只消费摘要；完整数据仍留在 lessons/variants/* 供课程页使用。
// 用法：pnpm academy:manifest（数据层改动后必须重新运行，守卫见 manifest.parity.test.ts）
import { createServer } from 'vite';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUT_DIR = path.join(ROOT, 'src/features/strategy-academy/data/lessons/manifest');

const HEADER = `// AUTO-GENERATED by scripts/generate-academy-manifest.mjs — do not edit.
// 数据层（lessons/variants/*）改动后运行 \`pnpm academy:manifest\` 重新生成。
import type { LevelSummary } from '../../../types';
`;

function projectLesson(lesson) {
  return {
    id: lesson.id,
    level: lesson.level,
    order: lesson.order,
    title: lesson.title,
    subtitle: lesson.subtitle,
    duration: lesson.duration,
    ...(lesson.type ? { type: lesson.type } : {}),
    variant: lesson.variant ?? 'standard',
    ...(lesson.prerequisites ? { prerequisites: lesson.prerequisites } : {}),
    hasPractice: Boolean(lesson.practice && lesson.practice.questions?.length > 0),
    quizCount: lesson.quiz?.length ?? 0,
  };
}

function projectLevel(level, lessons) {
  return {
    ...(level.id ? { id: level.id } : {}),
    level: level.level,
    title: level.title,
    description: level.description,
    icon: level.icon,
    unlockRequirement: level.unlockRequirement,
    ...(level.prerequisiteLevelIds ? { prerequisiteLevelIds: level.prerequisiteLevelIds } : {}),
    lessons: lessons.map(projectLesson),
  };
}

/** Level 字段逐行、Lesson 一行一个，避免生成文件触发 300 行规模守卫 */
function serializeLevels(levels) {
  return levels
    .map((level) => {
      const lessons = level.lessons
        .map((lesson) => `      ${JSON.stringify(lesson)},`)
        .join('\n');
      return `  {
    "level": ${level.level},
${level.id ? `    "id": ${JSON.stringify(level.id)},\n` : ''}    "title": ${JSON.stringify(level.title)},
    "description": ${JSON.stringify(level.description)},
    "icon": ${JSON.stringify(level.icon)},
    "unlockRequirement": ${JSON.stringify(level.unlockRequirement)},
${level.prerequisiteLevelIds ? `    "prerequisiteLevelIds": ${JSON.stringify(level.prerequisiteLevelIds)},\n` : ''}    "lessons": [
${lessons}
    ]
  },`;
    })
    .join('\n');
}

const server = await createServer({
  root: ROOT,
  server: { middlewareMode: true },
  appType: 'custom',
  logLevel: 'silent',
});

try {
  const courses = await server.ssrLoadModule(
    '/src/features/strategy-academy/data/courses.ts',
  );
  const variantIndex = await server.ssrLoadModule(
    '/src/features/strategy-academy/data/lessons/variants/index.ts',
  );

  const standard = courses.LEVELS.map((level) => projectLevel(level, level.lessons));
  /**
   * 变体 L4 合并展示：标准侧 L4 拆 l4a/l4b 两个条目，变体课只有一组 level:4 课程；
   * 若按数字 level 直接匹配标准条目会把同一组课重复挂到 l4a 与 l4b。
   * 这里按数字 level 去重，并为 L4 提供合并标题；id 保留 `l4b` 以维持
   * 标准 L8 `prerequisiteLevelIds: ['l4b']` 的可解析性。
   * 注意：`src/features/strategy-academy/data/lessons/manifest.parity.test.ts`
   * 的 expectedVariantLevels 必须与本逻辑保持同步。
   */
  const VARIANT_LEVEL_OVERRIDES = {
    4: {
      id: 'l4b',
      title: '进阶思维 · 范围、EV 与 GTO',
      description: '范围、EV 与 GTO 博弈的整合',
      icon: '🧠',
      unlockRequirement: '完成 Level 3 所有课程',
    },
  };
  const variantLevels = (variant) => {
    const byLevel = new Map();
    for (const lesson of variantIndex.VARIANT_LESSON_INDEX[variant]) {
      const list = byLevel.get(lesson.level) ?? [];
      list.push(lesson);
      byLevel.set(lesson.level, list);
    }
    const baseByLevel = new Map();
    for (const level of courses.LEVELS) {
      if (byLevel.has(level.level) && !baseByLevel.has(level.level)) {
        baseByLevel.set(level.level, level);
      }
    }
    return [...byLevel.entries()]
      .toSorted(([a], [b]) => a - b)
      .map(([levelNumber, lessons]) => {
        const base = baseByLevel.get(levelNumber);
        const override = VARIANT_LEVEL_OVERRIDES[levelNumber];
        return projectLevel({ ...base, ...override }, lessons);
      });
  };

  const files = [
    ['standard', 'STANDARD_LEVEL_SUMMARIES', standard],
    ['short-deck', 'SHORT_DECK_LEVEL_SUMMARIES', variantLevels('short-deck')],
    ['heads-up', 'HEADS_UP_LEVEL_SUMMARIES', variantLevels('heads-up')],
  ];

  for (const [file, exportName, levels] of files) {
    const lessons = levels.reduce((sum, level) => sum + level.lessons.length, 0);
    const body = `${HEADER}\nexport const ${exportName}: LevelSummary[] = [\n${serializeLevels(
      levels,
    )}\n];\n`;
    writeFileSync(path.join(OUT_DIR, `${file}.ts`), body);
    console.log(`[academy-manifest] ${file}.ts ← ${levels.length} levels / ${lessons} lessons`);
  }
} finally {
  await server.close();
}
